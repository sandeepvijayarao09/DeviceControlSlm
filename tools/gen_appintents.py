"""Generate Swift App Intents from the canonical command catalog.

Single source of truth: bench/tools/catalog.json drives (a) the model's command
set, (b) the benchmark, and now (c) the on-device App Intents. Regenerating
keeps all three in lock-step — a command can never exist in the model but be
missing from the app, or vice versa.

Emits one Swift file with:
  * AppEnum types for enum parameters (Focus mode, ringer mode, media action)
  * one `AppIntent` struct per command (Siri / Shortcuts / Spotlight surface)
  * a `DeviceControlling` protocol (the actual side-effect API, per-OS impls)
  * a `CommandRouter` that maps the model's DSL (tool + string args) to the
    controller — the SLM -> action bridge.

    python tools/gen_appintents.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "bench" / "tools" / "catalog.json"
OUT = ROOT / "apple" / "DeviceControlKit" / "Sources" / "DeviceControlKit" / "Generated" / "DeviceIntents.swift"

# nice Swift enum names for the catalog's enum parameters
ENUM_NAMES = {
    ("set_focus_mode", "mode"): "FocusMode",
    ("set_ringer_mode", "mode"): "RingerMode",
    ("media_control", "action"): "MediaAction",
}


def pascal(tool: str) -> str:
    return "".join(p.capitalize() for p in tool.split("_"))


def camel(tool: str) -> str:
    p = pascal(tool)
    return p[0].lower() + p[1:]


def title_of(tool: str) -> str:
    return " ".join(p.capitalize() for p in tool.split("_"))


def swift_type(tool, pname, pspec, required):
    if pspec.get("type") == "boolean":
        t = "Bool"
    elif pspec.get("type") == "integer":
        t = "Int"
    elif "enum" in pspec:
        t = ENUM_NAMES[(tool, pname)]
    else:
        t = "String"
    return t if required else t + "?"


def gen():
    catalog = json.loads(CATALOG.read_text())
    tools = catalog["tools"]
    L = []
    L.append("// GENERATED by tools/gen_appintents.py from bench/tools/catalog.json — do not edit by hand.")
    L.append("// Regenerate: python tools/gen_appintents.py")
    L.append("import AppIntents")
    L.append("import Foundation")
    L.append("")

    # ---- enums ----
    for (tool, pname), name in ENUM_NAMES.items():
        spec = next(p for t in tools if t["name"] == tool
                    for pn, p in t["parameters"]["properties"].items() if pn == pname)
        cases = spec["enum"]
        L.append(f"public enum {name}: String, AppEnum, CaseIterable {{")
        for c in cases:
            L.append(f"    case {c}")
        L.append(f"    public static var typeDisplayRepresentation: TypeDisplayRepresentation "
                 f"{{ \"{name}\" }}")
        L.append("    public static var caseDisplayRepresentations: [Self: DisplayRepresentation] {")
        L.append("        [" + ", ".join(f'.{c}: "{c.capitalize()}"' for c in cases) + "]")
        L.append("    }")
        L.append("}")
        L.append("")

    # ---- controller protocol ----
    L.append("/// The actual side-effect API. Per-OS implementations live in")
    L.append("/// DeviceController+iOS.swift / DeviceController+macOS.swift.")
    L.append("public protocol DeviceControlling {")
    for t in tools:
        props = t["parameters"].get("properties", {})
        req = set(t["parameters"].get("required", []))
        params = ", ".join(f"{p}: {swift_type(t['name'], p, s, p in req)}"
                           for p, s in props.items())
        ret = " -> String" if t["domain"] == "query" else ""
        L.append(f"    func {camel(t['name'])}({params}) async throws{ret}")
    L.append("}")
    L.append("")

    # ---- AppIntent structs ----
    for t in tools:
        name = t["name"]
        props = t["parameters"].get("properties", {})
        req = set(t["parameters"].get("required", []))
        L.append(f"public struct {pascal(name)}Intent: AppIntent {{")
        L.append(f'    public static var title: LocalizedStringResource = "{title_of(name)}"')
        L.append(f'    public static var description = IntentDescription("{t["description"]}")')
        L.append("    public init() {}")
        call_args = []
        for p, s in props.items():
            ty = swift_type(name, p, s, p in req)
            L.append(f'    @Parameter(title: "{p.capitalize()}") public var {p}: {ty}')
            call_args.append(f"{p}: {p}")
        L.append("    public func perform() async throws -> some IntentResult {")
        args = ", ".join(call_args)
        if t["domain"] == "query":
            # value is surfaced via CommandRouter for the model path; keep the
            # AppIntent result simple so it always compiles.
            L.append(f"        _ = try await DeviceControl.shared.{camel(name)}({args})")
        else:
            L.append(f"        try await DeviceControl.shared.{camel(name)}({args})")
        L.append("        return .result()")
        L.append("    }")
        L.append("}")
        L.append("")

    # ---- CommandRouter: model DSL -> controller ----
    L.append("/// Bridges the SLM's DSL output (tool name + string args) to the controller.")
    L.append("public enum CommandRouter {")
    L.append("    @discardableResult")
    L.append("    public static func run(tool: String, args: [String: String]) async throws -> String {")
    L.append("        let c = DeviceControl.shared")
    L.append("        switch tool {")
    for t in tools:
        name = t["name"]
        props = t["parameters"].get("properties", {})
        req = set(t["parameters"].get("required", []))
        conv = []
        for p, s in props.items():
            if s.get("type") == "boolean":
                default = "false"
                conv.append(f'{p}: (args["{p}"].map {{ $0 == "true" }} ?? {default})')
            elif s.get("type") == "integer":
                conv.append(f'{p}: Int(args["{p}"] ?? "") ?? 0')
            elif "enum" in s:
                en = ENUM_NAMES[(name, p)]
                if p in req:
                    conv.append(f'{p}: {en}(rawValue: args["{p}"] ?? "") ?? .{s["enum"][0]}')
                else:
                    conv.append(f'{p}: args["{p}"].flatMap {{ {en}(rawValue: $0) }}')
            else:
                conv.append(f'{p}: args["{p}"]' + ("" if p in req else ""))
        argstr = ", ".join(conv)
        if t["domain"] == "query":
            L.append(f'        case "{name}": return try await c.{camel(name)}({argstr})')
        else:
            L.append(f'        case "{name}": try await c.{camel(name)}({argstr}); return "{name} ok"')
    L.append("        default: throw DeviceControlError.unknownCommand(tool)")
    L.append("        }")
    L.append("    }")
    L.append("}")
    L.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(tools)} intents)")

    # ---- a compile-ready stub controller (logs + placeholders) ----
    S = []
    S.append("// GENERATED by tools/gen_appintents.py — do not edit by hand.")
    S.append("// A no-op controller so the package builds and runs in a Simulator/Preview.")
    S.append("// Replace with real per-OS calls (see DeviceController+iOS/macOS.swift).")
    S.append("import Foundation")
    S.append("")
    S.append("public final class StubDeviceController: DeviceControlling {")
    S.append("    public init() {}")
    for t in tools:
        name = t["name"]
        props = t["parameters"].get("properties", {})
        req = set(t["parameters"].get("required", []))
        params = ", ".join(f"{p}: {swift_type(name, p, s, p in req)}" for p, s in props.items())
        argnames = ", ".join(f"\\({p})" for p in props)
        ret = " -> String" if t["domain"] == "query" else ""
        S.append(f"    public func {camel(name)}({params}) async throws{ret} {{")
        S.append(f'        DeviceLog.emit("{name}", "{argnames}")')
        if t["domain"] == "query":
            S.append(f'        return "[stub] {name}"')
        S.append("    }")
    S.append("}")
    S.append("")
    S.append("public enum DeviceLog { public static func emit(_ cmd: String, _ args: String) {")
    S.append('    print("[DeviceControl] \\(cmd) \\(args)") } }')
    stub_out = OUT.parent / "StubDeviceController.swift"
    stub_out.write_text("\n".join(S) + "\n", encoding="utf-8")
    print(f"wrote {stub_out.relative_to(ROOT)}")


if __name__ == "__main__":
    gen()
